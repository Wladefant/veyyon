import * as fs from "node:fs/promises";
import * as path from "node:path";
import type { AgentSession } from "@veyyon/coding-agent";
import { resolveEditMode } from "@veyyon/coding-agent/utils/edit-mode";
import { errorMessage } from "@veyyon/utils";

export interface EditableCanaryReceipt {
	readonly version: 1;
	readonly passed: true;
	readonly mode: string;
	readonly blockAutoGenerated: boolean;
}

/** Exercise the session's real tools before a skill trial spends provider tokens. */
export async function verifyEditableCanary(session: AgentSession, cwd: string): Promise<EditableCanaryReceipt> {
	const read = session.agent.state.tools.find(tool => tool.name === "read");
	const edit = session.agent.state.tools.find(tool => tool.name === "edit");
	if (!read || !edit) throw new Error("Invalid eval harness: editable canary requires the real read and edit tools.");
	const model = session.model;
	const mode = resolveEditMode({ settings: session.settings, getActiveModelString: () => model ? `${model.provider}/${model.id}` : undefined });
	const directory = await fs.mkdtemp(path.join(cwd, ".veyyon-editable-canary-"));
	try {
		const file = path.join(directory, "canary.ts");
		const before = "export const canary = 1;\n";
		const after = "export const canary = 2;\n";
		await fs.writeFile(file, before);
		const observed = await read.execute("eval-canary-read", { path: file });
		const text = observed.content.filter(part => part.type === "text").map(part => part.text).join("\n");
		const header = text.match(/^\[.+#[0-9A-F]{4}\]$/m)?.[0];
		const input = mode === "hashline"
			? { input: `${header ?? ""}\nSWAP 1.=1:\n+${after}` }
			: mode === "apply_patch"
				? { input: `*** Begin Patch\n*** Update File: ${file}\n@@\n-${before.trimEnd()}\n+${after.trimEnd()}\n*** End Patch\n` }
				: mode === "patch"
					? { path: file, edits: [{ op: "update", diff: `@@\n-${before.trimEnd()}\n+${after.trimEnd()}\n` }] }
					: { path: file, old_string: before, new_string: after };
		if (mode === "hashline" && !header) throw new Error("Read did not expose an editable snapshot header.");
		await edit.execute("eval-canary-edit", input);
		if (await fs.readFile(file, "utf8") !== after) throw new Error("Edit did not produce the expected file bytes.");
		return { version: 1, passed: true, mode, blockAutoGenerated: session.settings.get("edit.blockAutoGenerated") };
	} catch (error) {
		throw new Error(`Invalid eval harness: isolated-session editable canary failed: ${errorMessage(error)}`, { cause: error });
	} finally {
		await fs.rm(directory, { recursive: true, force: true });
	}
}
