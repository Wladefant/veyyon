/**
 * WHY: A loaded skill was real but every solver edit failed through a global Settings read.
 * Drive SDK-created tools with isolated settings before any provider call. Sweep the actual
 * supported edit-mode set. A missing tool must fail closed, not become a zero-reward trial.
 * GAP: This does not measure model quality or validate a provider's request serialization.
 * The Linux test image lacks the native scan-cache addon. Only cache invalidation is stubbed;
 * the standalone native SDK doctor covers that boundary with no stub.
 */
import { expect, it, spyOn } from "bun:test";
import * as fs from "node:fs/promises";
import { AuthStorage } from "@veyyon/ai/auth-storage";
import { createMockModel } from "@veyyon/ai/providers/mock";
import { createAgentSession, ModelRegistry, SessionManager, Settings } from "@veyyon/coding-agent";
import { EDIT_MODE_STRATEGIES } from "@veyyon/coding-agent/edit/streaming";
import * as fsCache from "@veyyon/coding-agent/tools/core/fs-cache-invalidation";
import { TempDir } from "@veyyon/utils";
import { verifyEditableCanary } from "../../backends/in-process/editable-canary";

it("uses the real isolated SDK tools for every edit mode and refuses an uneditable session", async () => {
	const temp = await TempDir.create("eval-sdk-editable-doctor-");
	const auth = await AuthStorage.create(temp.join("auth.db"));
	const invalidation = spyOn(fsCache, "invalidateFsScanAfterWrite").mockImplementation(() => {});
	try {
		const mock = createMockModel({ handler: { content: ["must not run"] } });
		const registry = new ModelRegistry(auth, temp.join("models.yml"));
		for (const mode of Object.keys(EDIT_MODE_STRATEGIES)) {
			const settings = Settings.isolated({ "edit.mode": mode, "lsp.enabled": false, "read.summarize.enabled": false });
			const { session } = await createAgentSession({ cwd: temp.path(), model: mock.model, settings,
				authStorage: auth, modelRegistry: registry, sessionManager: SessionManager.inMemory(temp.path()),
				toolNames: ["read", "edit", "write"], enableMCP: false, enableLsp: false,
				skills: [], rules: [], contextFiles: [], disableExtensionDiscovery: true, hasUI: false });
			try {
				const receipt = await verifyEditableCanary(session, temp.path());
				expect(receipt).toEqual({ version: 1, passed: true, mode, blockAutoGenerated: settings.get("edit.blockAutoGenerated") });
				expect((await fs.readdir(temp.path())).filter(file => file.startsWith(".veyyon-editable-canary-"))).toEqual([]);
				const tools = session.agent.state.tools;
				session.agent.setTools(tools.filter(tool => tool.name !== "edit"));
				await expect(verifyEditableCanary(session, temp.path())).rejects.toThrow("editable canary requires the real read and edit tools");
				session.agent.setTools(tools);
			} finally {
				await session.dispose();
			}
		}
		expect(mock.calls).toEqual([]);
	} finally {
		invalidation.mockRestore();
		auth.close();
		await temp.remove();
	}
}, 120_000);
