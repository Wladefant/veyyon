import { afterEach, beforeEach, describe, expect, it, mock, spyOn } from "bun:test";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import type { AgentToolResult } from "@veyyon/agent-core";
import { resetSettingsForTest, Settings } from "@veyyon/coding-agent/config/settings";
import { type ExecuteHashlineSingleOptions, executeHashlineSingle } from "@veyyon/coding-agent/edit";
import type { ToolSession } from "@veyyon/coding-agent/tools";
import * as fsCache from "@veyyon/coding-agent/tools/core/fs-cache-invalidation";
import type { ReadToolDetails } from "@veyyon/coding-agent/tools/fs/read"
import { ReadTool } from "@veyyon/coding-agent/tools/fs/read";
import { removeWithRetries } from "@veyyon/utils";
import { hashlineExecOptions } from "./helpers/hashline-exec";
import { toolResultText } from "./helpers/tool-result-text";
import { makeToolSession } from "./helpers/tool-session";

beforeAll(async () => {
	// The edit path's auto-generated-file guard reads the global Settings proxy.
	resetSettingsForTest();
	await Settings.init({ inMemory: true, cwd: process.cwd() });
});

function textOutput(result: AgentToolResult<ReadToolDetails>): string {
	return result.content
		.filter(c => c.type === "text")
		.map(c => c.text)
		.join("\n");
}

function createSession(cwd: string, blockAutoGenerated = false): ToolSession {
	const settings = Settings.isolated();
	settings.set("read.summarize.enabled", false);
	settings.set("edit.blockAutoGenerated", blockAutoGenerated);
	return makeToolSession({
		cwd,
		hasUI: false,
		getSessionFile: () => path.join(cwd, "session.jsonl"),
		getSessionSpawns: () => "*",
		getArtifactsDir: () => path.join(cwd, "artifacts"),
		allocateOutputArtifact: async () => ({ id: "artifact-1", path: path.join(cwd, "artifact-1.log") }),
		settings,
	});
}

// Regression: reading a file *outside* the session cwd (e.g. `~/.claude/settings.json`)
// and then editing it anchored on the emitted hashline header. The header used to
// collapse to the bare filename for every read; out-of-tree the edit tool's
// snapshot-tag recovery refuses to rebind a bare name (allowTagPathRecovery), so the
// path resolved against cwd, missed, and failed with "File not found". The header now
// carries the full out-of-cwd path so the edit resolves directly.
describe("read → edit round-trip for out-of-cwd files", () => {
	let cwdDir: string;
	let outDir: string;

	beforeEach(async () => {
		// The Linux test image has no native scan-cache addon; file writes remain real.
		spyOn(fsCache, "invalidateFsScanAfterWrite").mockImplementation(() => {});
		cwdDir = await fs.mkdtemp(path.join(os.tmpdir(), "read-edit-cwd-"));
		outDir = await fs.mkdtemp(path.join(os.tmpdir(), "read-edit-out-"));
	});

	afterEach(async () => {
		mock.restore();
		await removeWithRetries(cwdDir);
		await removeWithRetries(outDir);
	});

	it("anchors the out-of-cwd path in the header so a follow-up edit lands", async () => {
		const outFile = path.join(outDir, "settings.json");
		await fs.writeFile(outFile, "alpha\nbeta\n");

		const session = createSession(cwdDir);
		const header = toolResultText(await new ReadTool(session).execute("read-out", { path: outFile })).split("\n")[0];

		// The header must carry the directory, not just `settings.json`, or the
		// edit below would resolve the bare name against cwdDir and miss.
		expect(header).toMatch(/^\[.+settings\.json#[0-9A-F]{4}\]$/);
		expect(header).toContain(path.basename(outDir));

		const result = await executeHashlineSingle(hashlineExecOptions(`${header}\nSWAP 1.=1:\n+ALPHA\n`, session));
		const resultText = result.content.map(part => (part.type === "text" ? part.text : "")).join("\n");

		expect(resultText).not.toContain("File not found");
		expect(await Bun.file(outFile).text()).toBe("ALPHA\nbeta\n");
	});

	it("still collapses an in-cwd read header to the bare filename", async () => {
		const inFile = path.join(cwdDir, "src", "settings.json");
		await fs.mkdir(path.dirname(inFile), { recursive: true });
		await fs.writeFile(inFile, "alpha\nbeta\n");

		const session = createSession(cwdDir);
		const header = toolResultText(await new ReadTool(session).execute("read-in", { path: inFile })).split("\n")[0];

		expect(header).toMatch(/^\[settings\.json#[0-9A-F]{4}\]$/);
		expect(header).not.toContain("src");
	});

	it("keeps generated-file protection local to each isolated edit session", async () => {
		const file = path.join(cwdDir, "generated.ts");
		const original = "// @generated\nexport const value = 1;\n";
		await fs.writeFile(file, original);
		const blocked = createSession(cwdDir, true);
		const allowed = createSession(cwdDir, false);
		const header = textOutput(await new ReadTool(allowed).execute("read-generated", { path: file })).split("\n")[0];
		const patch = `${header}\nSWAP 2.=2:\n+export const value = 2;\n`;
		await expect(executeHashlineSingle(editOptions(blocked, patch))).rejects.toThrow(
			"Cannot modify auto-generated file",
		);
		expect(await fs.readFile(file, "utf8")).toBe(original);
		await executeHashlineSingle(editOptions(allowed, patch));
		expect(await fs.readFile(file, "utf8")).toBe("// @generated\nexport const value = 2;\n");
	});
});
