import { afterAll, beforeAll, describe, expect, it } from "bun:test";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import { ToolError } from "@veyyon/coding-agent/tools/core/tool-errors";
import { assertEditableFile, assertEditableFileContent } from "@veyyon/coding-agent/tools/fs/auto-generated-guard";
import { removeWithRetries } from "@veyyon/utils";

let tempDir: string;
beforeAll(async () => {
	tempDir = await fs.mkdtemp(path.join(os.tmpdir(), "auto-gen-guard-"));
});
afterAll(async () => {
	await removeWithRetries(tempDir);
});

describe("assertEditableFileContent", () => {
	it.each([
		[
			"canonical TypeScript generated header",
			"test.ts",
			"// Code generated by sqlc. DO NOT EDIT.\n\nexport const foo = 1;",
		],
		["@generated marker", "test.ts", "// @generated\n\nexport const foo = 1;"],
		["Python generated-by marker", "test.py", "# Generated by buf\n\nvalue = 1"],
		["SQL generated-by marker", "query.sql", "-- generated by sqlc\n\nselect 1;"],
		[
			"leading block comment",
			"test.ts",
			"/*\n * Code generated by mockery. DO NOT EDIT.\n */\nexport const foo = 1;",
		],
		[
			"kysely-codegen header",
			"db.ts",
			"/**\n * This file was generated by kysely-codegen.\n * Please do not edit it manually.\n */\n\nexport interface Database {}",
		],
	])("detects %s", (_name, file, content) => {
		expect(() => assertEditableFileContent(content, true, file)).toThrow(ToolError);
	});
});

describe("assertEditableFile", () => {
	it("detects content marker from file prefix and preserves its display path", async () => {
		const filePath = path.join(tempDir, "service.ts");
		await fs.writeFile(
			filePath,
			`// Code generated by sqlc. DO NOT EDIT.\nexport const foo = 1;\n${"// padding line\n".repeat(400)}`,
		);
		const error = await assertEditableFile(filePath, true, "src/service.ts").then(
			() => undefined,
			(caught: unknown) => caught,
		);
		expect(error).toBeInstanceOf(ToolError);
		if (!(error instanceof ToolError)) throw new Error("expected generated-file refusal");
		expect(error.message).toContain("Cannot modify auto-generated file: src/service.ts");
		expect(error.message).toContain('detected marker: "Code generated by sqlc."');
	});
	it("allows normal files", async () => {
		const filePath = path.join(tempDir, "normal.ts");
		await fs.writeFile(filePath, "// Regular source file\nexport const foo = 1;");
		await expect(assertEditableFile(filePath, true)).resolves.toBeUndefined();
	});
	it("handles missing files gracefully", async () => {
		await expect(assertEditableFile(path.join(tempDir, "does-not-exist.ts"), true)).resolves.toBeUndefined();
	});
	it("allows handwritten files named generated.go without generator header", async () => {
		const filePath = path.join(tempDir, "generated.go");
		await fs.writeFile(filePath, "package p\n\n// Handwritten code with no generator header.\nfunc Run() {}\n");
		await expect(assertEditableFile(filePath, true)).resolves.toBeUndefined();
	});
	it("refuses generated.go when it carries a code generated marker", async () => {
		const filePath = path.join(tempDir, "generated.go");
		await fs.writeFile(filePath, "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage p\n\nfunc Run() {}\n");
		await expect(assertEditableFile(filePath, true)).rejects.toThrow(ToolError);
	});
});
